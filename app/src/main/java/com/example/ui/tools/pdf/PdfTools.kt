@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun TextToPdfScreen(onBack: () -> Unit) {
    BackHandler { onBack() }
    val context = LocalContext.current

    var docTitle by remember { mutableStateOf("Project Specification Document") }
    var docAuthor by remember { mutableStateOf("OmniTools Author") }
    var docContent by remember {
        mutableStateOf(
            "This document was created directly using OmniTools.\n\n" +
            "Key Features:\n" +
            "• Clean PDF formatting and pagination\n" +
            "• Standard A4 document canvas (595 x 842 points)\n" +
            "• Instant PDF export and WhatsApp/Email sharing\n\n" +
            "Thank you for choosing OmniTools All-in-One Utility Kit!"
        )
    }

    fun generateAndSharePdf(title: String, author: String, content: String, isShare: Boolean) {
        try {
            val pdfDoc = PdfDocument()
            val pageInfo = PdfDocument.PageInfo.Builder(595, 842, 1).create() // A4 size
            val page = pdfDoc.startPage(pageInfo)
            val canvas = page.canvas

            val paint = Paint().apply {
                isAntiAlias = true
                color = AndroidColor.BLACK
            }

            // Title
            paint.textSize = 24f
            paint.isFakeBoldText = true
            canvas.drawText(title, 40f, 60f, paint)

            // Author & Date
            paint.textSize = 12f
            paint.isFakeBoldText = false
            paint.color = AndroidColor.DKGRAY
            canvas.drawText("Author: $author  |  Generated by OmniTools", 40f, 85f, paint)

            paint.color = AndroidColor.LTGRAY
            paint.strokeWidth = 1f
            canvas.drawLine(40f, 100f, 555f, 100f, paint)

            // Body text
            paint.color = AndroidColor.BLACK
            paint.textSize = 13f
            var currentY = 130f
            val lines = content.split("\n")
            for (line in lines) {
                if (currentY > 800f) break
                canvas.drawText(line, 40f, currentY, paint)
                currentY += 20f
            }

            pdfDoc.finishPage(page)

            val file = File(context.cacheDir, "OmniTools_Doc_${System.currentTimeMillis()}.pdf")
            val outputStream = FileOutputStream(file)
            pdfDoc.writeTo(outputStream)
            pdfDoc.close()
            outputStream.close()

            val uri: Uri = FileProvider.getUriForFile(context, "${context.packageName}.provider", file)
            if (isShare) {
                val shareIntent = Intent(Intent.ACTION_SEND).apply {
                    type = "application/pdf"
                    putExtra(Intent.EXTRA_STREAM, uri)
                    putExtra(Intent.EXTRA_SUBJECT, title)
                    addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
                }
                context.startActivity(Intent.createChooser(shareIntent, "Share PDF"))
            } else {
                Toast.makeText(context, "PDF saved to app documents cache!", Toast.LENGTH_SHORT).show()
            }
        } catch (e: Exception) {
            Toast.makeText(context, "Error generating PDF: ${e.message}", Toast.LENGTH_SHORT).show()
        }
    }

    Scaffold(
        topBar = {
            Column {
                TopBannerAd()
                TopAppBar(
                    title = { Text("Text → PDF Maker") },
                    navigationIcon = {
                        IconButton(onClick = onBack) {
                            Icon(Icons.AutoMirrored.Filled.ArrowBack, contentDescription = "Back")
                        }
                    },
                    colors = TopAppBarDefaults.topAppBarColors(containerColor = MaterialTheme.colorScheme.surface)
                )
            }
        }
    ) { padding ->
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(padding)
                .verticalScroll(rememberScrollState())
                .padding(16.dp),
            verticalArrangement = Arrangement.spacedBy(16.dp)
        ) {
            OutlinedTextField(value = docTitle, onValueChange = { docTitle = it }, label = { Text("Document Title") }, modifier = Modifier.fillMaxWidth())
            OutlinedTextField(value = docAuthor, onValueChange = { docAuthor = it }, label = { Text("Author Name") }, modifier = Modifier.fillMaxWidth())
            OutlinedTextField(
                value = docContent,
                onValueChange = { docContent = it },
                label = { Text("Document Content / Paragraphs") },
                modifier = Modifier.fillMaxWidth(),
                minLines = 8
            )

            Row(modifier = Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.spacedBy(12.dp)) {
                Button(
                    onClick = { generateAndSharePdf(docTitle, docAuthor, docContent, isShare = false) },
                    modifier = Modifier.weight(1f)
                ) {
                    Icon(Icons.Filled.PictureAsPdf, contentDescription = null, modifier = Modifier.size(18.dp))
                    Spacer(Modifier.width(6.dp))
                    Text("Export PDF")
                }
                OutlinedButton(
                    onClick = { generateAndSharePdf(docTitle, docAuthor, docContent, isShare = true) },
                    modifier = Modifier.weight(1f)
                ) {
                    Icon(Icons.Filled.Share, contentDescription = null, modifier = Modifier.size(18.dp))
                    Spacer(Modifier.width(6.dp))
                    Text("Share PDF")
                }
            }
        }
    }
}

