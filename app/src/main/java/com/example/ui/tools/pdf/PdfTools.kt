@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun CaseConverterScreen(onBack: () -> Unit) {
    BackHandler { onBack() }
    val context = LocalContext.current

    var inputText by remember { mutableStateOf("hello world from omnitools") }

    val conversions = listOf(
        "UPPERCASE" to inputText.uppercase(),
        "lowercase" to inputText.lowercase(),
        "Title Case" to inputText.split(" ").joinToString(" ") { it.replaceFirstChar { c -> c.uppercase() } },
        "Sentence case" to inputText.lowercase().replaceFirstChar { it.uppercase() },
        "camelCase" to inputText.split(" ").mapIndexed { idx, s -> if (idx == 0) s.lowercase() else s.lowercase().replaceFirstChar { it.uppercase() } }.joinToString(""),
        "snake_case" to inputText.lowercase().replace(" ", "_"),
        "kebab-case" to inputText.lowercase().replace(" ", "-"),
        "Alternating cAsE" to inputText.mapIndexed { i, c -> if (i % 2 == 0) c.lowercaseChar() else c.uppercaseChar() }.joinToString("")
    )

    Scaffold(
        topBar = {
            Column {
                TopBannerAd()
                TopAppBar(
                    title = { Text("Case Converter") },
                    navigationIcon = {
                        IconButton(onClick = onBack) {
                            Icon(Icons.AutoMirrored.Filled.ArrowBack, contentDescription = "Back")
                        }
                    },
                    colors = TopAppBarDefaults.topAppBarColors(containerColor = MaterialTheme.colorScheme.surface)
                )
            }
        }
    ) { padding ->
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(padding)
                .verticalScroll(rememberScrollState())
                .padding(16.dp),
            verticalArrangement = Arrangement.spacedBy(16.dp)
        ) {
            OutlinedTextField(
                value = inputText,
                onValueChange = { inputText = it },
                label = { Text("Input Text to Convert") },
                modifier = Modifier.fillMaxWidth()
            )

            conversions.forEach { (type, converted) ->
                Card(
                    modifier = Modifier.fillMaxWidth(),
                    colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surfaceVariant.copy(alpha = 0.5f))
                ) {
                    Row(
                        modifier = Modifier
                            .fillMaxWidth()
                            .padding(12.dp),
                        horizontalArrangement = Arrangement.SpaceBetween,
                        verticalAlignment = Alignment.CenterVertically
                    ) {
                        Column(modifier = Modifier.weight(1f)) {
                            Text(type, fontSize = 11.sp, fontWeight = FontWeight.Bold, color = MaterialTheme.colorScheme.primary)
                            Text(converted, fontSize = 14.sp, fontWeight = FontWeight.Medium)
                        }
                        IconButton(
                            onClick = { ImageExportUtils.copyToClipboard(context, converted, type) }
                        ) {
                            Icon(Icons.Filled.ContentCopy, contentDescription = "Copy", modifier = Modifier.size(18.dp))
                        }
                    }
                }
            }
        }
    }
}
