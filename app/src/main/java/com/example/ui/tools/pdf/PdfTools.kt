@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun WordAndCharacterCounterScreen(onBack: () -> Unit) {
    BackHandler { onBack() }
    val context = LocalContext.current

    var textInput by remember { mutableStateOf("The quick brown fox jumps over the lazy dog. OmniTools makes productivity simple and fast!") }

    val charCount = textInput.length
    val charNoSpaces = textInput.replace(" ", "").replace("\n", "").length
    val words = textInput.trim().split("\\s+".toRegex()).filter { it.isNotBlank() }
    val wordCount = words.size
    val sentenceCount = textInput.split("[.!?]+".toRegex()).filter { it.isNotBlank() }.size
    val paragraphCount = textInput.split("\n\n").filter { it.isNotBlank() }.size

    // Average reading speed = 200 words per minute, Speaking = 130 wpm
