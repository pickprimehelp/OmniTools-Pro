                        Text("Sentences:")
                        Text("$sentenceCount", fontWeight = FontWeight.SemiBold)
                    }
                    Row(modifier = Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.SpaceBetween) {
                        Text("Paragraphs:")
                        Text("$paragraphCount", fontWeight = FontWeight.SemiBold)
