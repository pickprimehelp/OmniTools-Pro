    val speakingTimeSec = (wordCount * 60) / 130

    Scaffold(
        topBar = {
            Column {
                TopBannerAd()
                TopAppBar(
                    title = { Text("Word & Character Counter") },
                    navigationIcon = {
                        IconButton(onClick = onBack) {
